"""The curated episode library, as DATA: places, fetch windows, and every event with its source.

``scripts/build_research_cache.py`` reads this, fetches the series/scenes for each place and writes
``data/research/episodes.json`` (this spec plus the computed coverage). Nothing political: the
categories ``trade_policy`` and ``security`` exist in the enum but no episode uses them (content
rule: no war or political content).

An event's ``src`` is either an explicit ``{publisher, url, date}`` or ``("fig", episode, name)``,
which resolves ``source_name`` / ``source_url`` from ``data/sim_backtest/<dir>/actuals.json`` so the
library cites exactly what the sim backtest already cites. ``date_basis`` says whether ``date`` is the
publisher's publication date ("published") or the event date used because the publication date is
not recorded ("event").
"""
from __future__ import annotations


def ev(slug, t, category, title, src, place=None, t_end=None, date=None, basis="event"):
    return {"slug": slug, "t": t, "t_end": t_end, "category": category, "title": title,
            "place": place, "src": src, "date": date or t[:10], "date_basis": basis}


def fig(directory, name):
    return ("fig", directory, name)


