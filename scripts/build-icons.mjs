#!/usr/bin/env node
// Builds web/app/src/ui/iconData.ts from the vendored Lucide SVGs in
// web/app/src/ui/vendor/lucide/ (ISC licence, see THIRD-PARTY.md).
//
// node + fs only: no npm dependency, no network. The icon set is the
// allow-list below; every name must have a vendored <name>.svg. To add an
// icon: copy its SVG from lucide-static (same version as the others) into
// the vendor folder, add the name here, run `node scripts/build-icons.mjs`.
//
// Output: for each icon the list of its drawing elements as [tag, attrs]
// tuples. The <Icon> component renders them with React.createElement, so
// no innerHTML is involved and no icon font or sprite has to be mounted.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendor = join(root, 'web/app/src/ui/vendor/lucide');
const out = join(root, 'web/app/src/ui/iconData.ts');

export const ALLOW = [
  // controls
  'x', 'ellipsis', 'plus', 'minus', 'check', 'search', 'command', 'corner-down-left', 'delete',
  'chevron-down', 'chevron-up', 'chevron-left', 'chevron-right', 'chevrons-up-down',
  'arrow-right', 'arrow-left', 'arrow-up', 'arrow-down', 'arrow-up-right', 'arrow-left-right', 'external-link',
  'copy', 'download', 'upload', 'funnel', 'list', 'table', 'settings', 'sliders-horizontal', 'layers', 'ruler',
  'mouse-pointer-2', 'maximize-2', 'minimize-2', 'grip-vertical', 'eye', 'eye-off', 'pin', 'lock', 'link',
  'refresh-cw', 'rotate-ccw', 'save', 'trash-2', 'pencil', 'keyboard', 'terminal', 'loader-circle',
  // theme and AI
  'sun', 'moon', 'sparkles', 'mic', 'volume-2', 'volume-x', 'square',
  // transport and time
  'play', 'pause', 'skip-back', 'skip-forward', 'step-back', 'step-forward', 'history', 'clock', 'calendar', 'hourglass',
  // windows and places
  'house', 'layout-dashboard', 'layout-grid', 'panel-left', 'panel-top', 'columns-2', 'rows-2', 'square-stack',
  'map', 'globe', 'satellite', 'newspaper', 'network', 'waypoints', 'ship', 'anchor', 'factory', 'package', 'truck', 'plane',
  // analysis
  'chart-bar', 'chart-line', 'activity', 'flask-conical', 'scale', 'file-text', 'file-down', 'file-spreadsheet', 'book-open',
  'shield-check', 'database', 'git-fork', 'coins', 'gauge', 'zap', 'bell', 'user', 'target', 'crosshair', 'radio', 'signal',
  // status
  'wifi-off', 'ban', 'circle-alert', 'triangle-alert', 'info', 'circle-help', 'circle', 'circle-dot', 'circle-dashed',
  'circle-check', 'circle-x', 'circle-minus',
];

const ELEMENT = /<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g;
const ATTR = /([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g;

export function parseSvg(src) {
  const body = src.slice(src.indexOf('<svg'));
  const els = [];
  for (const m of body.matchAll(ELEMENT)) {
    const attrs = {};
    for (const a of m[2].matchAll(ATTR)) attrs[a[1]] = a[2];
    els.push([m[1], attrs]);
  }
  return els;
}

export function build() {
  const lines = [
    '// GENERATED by scripts/build-icons.mjs from src/ui/vendor/lucide (ISC, see THIRD-PARTY.md). Do not edit.',
    'export type IconEl = readonly [tag: string, attrs: Readonly<Record<string, string>>];',
    'export const ICON_DATA = {',
  ];
  const missing = [];
  for (const name of ALLOW) {
    const file = join(vendor, `${name}.svg`);
    if (!existsSync(file)) { missing.push(name); continue; }
    const els = parseSvg(readFileSync(file, 'utf8'));
    if (!els.length) throw new Error(`no drawing elements parsed from ${name}.svg`);
    lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(els)},`);
  }
  if (missing.length) throw new Error(`missing vendored svg: ${missing.join(', ')}`);
  lines.push('} as const satisfies Record<string, readonly IconEl[]>;', '', 'export type IconName = keyof typeof ICON_DATA;', 'export const ICON_NAMES = Object.keys(ICON_DATA) as IconName[];', '');
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(out, build());
  console.log(`wrote ${out} (${ALLOW.length} icons)`);
}
